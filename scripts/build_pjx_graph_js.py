"""One-off generator for pyjinhx/builtins/ui/pjx_graph/pjx_graph.js.

A builtin ships exactly one script, so the graph's asset is the vendored d3
subset (src/d3.vendor.js) followed by the engine (src/engine.js), inside one
function wrapper that keeps the vendored ``__pjxD3`` binding off ``window``.
Not imported by the package; needs no network or Node.js, and is run manually
after editing either source:

    uv run python scripts/build_pjx_graph_js.py

A test compares the committed file with ``build()``, so a stale asset fails CI.
"""

from pathlib import Path

GRAPH_DIR = Path(__file__).resolve().parents[1] / "pyjinhx/builtins/ui/pjx_graph"
D3_SOURCE = GRAPH_DIR / "src/d3.vendor.js"
ENGINE_SOURCE = GRAPH_DIR / "src/engine.js"
OUT = GRAPH_DIR / "pjx_graph.js"

BANNER = (
    "/* Generated by scripts/build_pjx_graph_js.py"
    " from src/d3.vendor.js + src/engine.js; do not edit. */\n"
)


def build() -> str:
    """The full text of pjx_graph.js, built from the two sources without writing anything."""
    parts = []
    for source in (D3_SOURCE, ENGINE_SOURCE):
        text = source.read_text(encoding="utf-8")
        # Without its own newline a source's last statement would share a line
        # with the next part.
        if not text.endswith("\n"):
            raise ValueError(f"{source} must end with a newline")
        parts.append(text)
    return BANNER + "(function () {\n" + "".join(parts) + "})();\n"


def main() -> None:
    text = build()
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote pjx_graph.js ({len(text.encode('utf-8'))} bytes) to {OUT}")


if __name__ == "__main__":
    main()
