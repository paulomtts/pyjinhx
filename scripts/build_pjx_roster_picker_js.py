"""One-off generator for pyjinhx/builtins/ui/pjx_roster_picker/pjx_roster_picker.js.

A builtin ships exactly one script, and the picker needs ``pjx.popoverPosition``,
so its asset is the popover placement primitive (../pjx_popover/pjx_popover_position.js)
followed by the picker (src/picker.js). Generating it keeps one source for the
primitive, shared with PJXPopover, instead of a hand-kept copy. Both sources are
already self-contained functions, so no outer wrapper is added. Not imported by the
package; needs no network or Node.js, and is run manually after editing either source:

    uv run python scripts/build_pjx_roster_picker_js.py

A test compares the committed file with ``build()``, so a stale asset fails CI.
"""

from pathlib import Path

PICKER_DIR = (
    Path(__file__).resolve().parents[1] / "pyjinhx/builtins/ui/pjx_roster_picker"
)
POPOVER_SOURCE = PICKER_DIR.parent / "pjx_popover/pjx_popover_position.js"
PICKER_SOURCE = PICKER_DIR / "src/picker.js"
OUT = PICKER_DIR / "pjx_roster_picker.js"

BANNER = (
    "/* Generated by scripts/build_pjx_roster_picker_js.py"
    " from ../pjx_popover/pjx_popover_position.js + src/picker.js; do not edit. */\n"
)


def build() -> str:
    """The full text of pjx_roster_picker.js, built from the two sources without writing anything."""
    parts = []
    for source in (POPOVER_SOURCE, PICKER_SOURCE):
        text = source.read_text(encoding="utf-8")
        # Without its own newline a source's last statement would share a line
        # with the next part.
        if not text.endswith("\n"):
            raise ValueError(f"{source} must end with a newline")
        parts.append(text)
    return BANNER + "".join(parts)
