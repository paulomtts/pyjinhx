"""The single pjx_roster_picker.js asset: its picker source, its build script, and the committed output.

Every check compares file bytes or a pure function's return value, so no page is needed.
"""

import importlib.util
from pathlib import Path
from types import ModuleType

import pytest

ROOT = Path(__file__).resolve().parents[4]
PICKER_DIR = ROOT / "pyjinhx" / "builtins" / "ui" / "pjx_roster_picker"
PICKER = PICKER_DIR / "src" / "picker.js"
POPOVER = (
    ROOT / "pyjinhx" / "builtins" / "ui" / "pjx_popover" / "pjx_popover_position.js"
)
SCRIPT = ROOT / "scripts" / "build_pjx_roster_picker_js.py"

BANNER = (
    "/* Generated by scripts/build_pjx_roster_picker_js.py"
    " from ../pjx_popover/pjx_popover_position.js + src/picker.js; do not edit. */\n"
)


def _load_script() -> ModuleType:
    # scripts/ is not a package, so the build script is loaded by path.
    spec = importlib.util.spec_from_file_location("build_pjx_roster_picker_js", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_picker_source_is_one_guarded_iife():
    source = PICKER.read_text(encoding="utf-8")
    assert source.startswith("(function () {")
    assert source.endswith("})();\n")
    assert "window.pjx.rosterPicker" in source


def test_picker_source_is_lf_only():
    assert b"\r" not in PICKER.read_bytes()


def test_build_is_banner_then_popover_primitive_then_picker():
    output = _load_script().build()
    primitive = POPOVER.read_text(encoding="utf-8")
    picker = PICKER.read_text(encoding="utf-8")
    assert output == BANNER + primitive + picker
    assert output.index(primitive) < output.index(picker)


def test_build_embeds_the_popover_primitive_exactly_once():
    output = _load_script().build()
    assert output.count(POPOVER.read_text(encoding="utf-8")) == 1
    # The primitive's one assignment: a second would mean placement code was
    # copied into src/picker.js instead of calling pjx.popoverPosition.
    assert output.count("pjx.popoverPosition =") == 1


@pytest.mark.parametrize("bad", ["POPOVER_SOURCE", "PICKER_SOURCE"])
def test_build_rejects_a_source_without_trailing_newline(tmp_path, monkeypatch, bad):
    script = _load_script()
    good_popover = tmp_path / "pjx_popover_position.js"
    good_popover.write_text("(function () {}());\n", encoding="utf-8")
    good_picker = tmp_path / "picker.js"
    good_picker.write_text("(function () {})();\n", encoding="utf-8")
    monkeypatch.setattr(script, "POPOVER_SOURCE", good_popover)
    monkeypatch.setattr(script, "PICKER_SOURCE", good_picker)
    unterminated = tmp_path / "unterminated.js"
    unterminated.write_text("var x = 1;", encoding="utf-8")
    monkeypatch.setattr(script, bad, unterminated)

    with pytest.raises(ValueError) as excinfo:
        script.build()
    assert str(unterminated) in str(excinfo.value)
    assert "must end with a newline" in str(excinfo.value)


@pytest.mark.parametrize("missing", ["POPOVER_SOURCE", "PICKER_SOURCE"])
def test_build_propagates_a_missing_source(tmp_path, monkeypatch, missing):
    script = _load_script()
    monkeypatch.setattr(script, missing, tmp_path / "missing.js")
    with pytest.raises(FileNotFoundError):
        script.build()
