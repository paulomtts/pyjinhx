"""The single pjx_graph.js asset: its engine source, its build script, and the committed output.

The static checks compare bytes. The behaviour checks load the real asset in
chromium, since only a running page can show what the file leaves on window.
"""

from __future__ import annotations

import importlib.util
from collections.abc import Iterator
from pathlib import Path
from types import ModuleType
from typing import TYPE_CHECKING, Any

import pytest

from pyjinhx.builtins.ui.pjx_graph import PJXGraph
from pyjinhx.rendering import render

if TYPE_CHECKING:
    from playwright.sync_api import Page

ROOT = Path(__file__).resolve().parents[4]
GRAPH_DIR = ROOT / "pyjinhx" / "builtins" / "ui" / "pjx_graph"
ENGINE = GRAPH_DIR / "src" / "engine.js"
D3 = GRAPH_DIR / "src" / "d3.vendor.js"
SCRIPT = ROOT / "scripts" / "build_pjx_graph_js.py"
ASSET = GRAPH_DIR / "pjx_graph.js"

BANNER = (
    "/* Generated by scripts/build_pjx_graph_js.py"
    " from src/d3.vendor.js + src/engine.js; do not edit. */\n"
)


def _load_script() -> ModuleType:
    # scripts/ is not a package, so the build script is loaded by path.
    spec = importlib.util.spec_from_file_location("build_pjx_graph_js", SCRIPT)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(autouse=True)
def _require_chromium(request: pytest.FixtureRequest) -> None:
    # Function-scoped so a missing browser skips only the tests that ask for
    # a page, mirroring tests/pyjinhx/client/conftest.py.
    if "page" not in set(request.fixturenames):
        return
    pytest.importorskip("playwright")
    browser_type: Any = request.getfixturevalue("browser_type")
    if not Path(browser_type.executable_path).exists():
        pytest.skip(
            "chromium is not installed (run: uv run playwright install chromium)"
        )


@pytest.fixture
def page_errors(page: Page) -> list[str]:
    """Every uncaught error the page throws from here on."""
    errors: list[str] = []
    page.on("pageerror", lambda error: errors.append(str(error)))
    return errors


@pytest.fixture
def graph_page(page: Page, page_errors: list[str]) -> Iterator[Page]:
    """A blank page with the asset loaded once as a classic script."""
    page.set_content("<body></body>")
    page.add_script_tag(content=ASSET.read_text(encoding="utf-8"))
    yield page


def test_engine_source_is_one_guarded_iife():
    source = ENGINE.read_text(encoding="utf-8")
    assert source.startswith("(function () {")
    assert source.endswith("})();\n")
    assert "window.pjx.graph" in source


def test_engine_source_is_lf_only():
    assert b"\r" not in ENGINE.read_bytes()


def test_build_puts_d3_before_engine_inside_one_wrapper():
    output = _load_script().build()
    d3 = D3.read_text(encoding="utf-8")
    engine = ENGINE.read_text(encoding="utf-8")
    assert output.startswith(BANNER + "(function () {\n")
    assert output.endswith("})();\n")
    assert output == BANNER + "(function () {\n" + d3 + engine + "})();\n"
    assert output.index(d3) < output.index(engine)


@pytest.mark.parametrize("bad", ["D3_SOURCE", "ENGINE_SOURCE"])
def test_build_rejects_a_source_without_trailing_newline(tmp_path, monkeypatch, bad):
    script = _load_script()
    good_d3 = tmp_path / "d3.vendor.js"
    good_d3.write_text("var __pjxD3=1;\n", encoding="utf-8")
    good_engine = tmp_path / "engine.js"
    good_engine.write_text("(function () {})();\n", encoding="utf-8")
    monkeypatch.setattr(script, "D3_SOURCE", good_d3)
    monkeypatch.setattr(script, "ENGINE_SOURCE", good_engine)
    unterminated = tmp_path / "unterminated.js"
    unterminated.write_text("var x = 1;", encoding="utf-8")
    monkeypatch.setattr(script, bad, unterminated)

    with pytest.raises(ValueError) as excinfo:
        script.build()
    assert str(unterminated) in str(excinfo.value)


def test_build_propagates_a_missing_source(tmp_path, monkeypatch):
    script = _load_script()
    monkeypatch.setattr(script, "ENGINE_SOURCE", tmp_path / "missing.js")
    with pytest.raises(FileNotFoundError):
        script.build()


def test_main_writes_the_build_byte_identically_twice(tmp_path, monkeypatch, capsys):
    script = _load_script()
    out = tmp_path / "pjx_graph.js"
    monkeypatch.setattr(script, "OUT", out)

    script.main()
    first = out.read_bytes()
    script.main()

    assert first == script.build().encode("utf-8")
    assert out.read_bytes() == first
    assert b"\r" not in first
    assert str(out) in capsys.readouterr().out


def test_committed_asset_matches_a_fresh_build():
    assert ASSET.read_bytes() == _load_script().build().encode("utf-8"), (
        "pjx_graph.js is stale: run `uv run python scripts/build_pjx_graph_js.py`"
    )


def test_asset_is_lf_only():
    assert b"\r" not in ASSET.read_bytes()


def test_script_is_frozen_on_the_descriptor():
    js = PJXGraph.__pjx_descriptor__.js_paths
    assert len(js) == 1
    assert js[0].name == "pjx_graph.js"
    assert js[0].is_file()


def test_render_accumulates_both_assets_into_the_session(session):
    from pyjinhx.session import accumulate_assets

    session.on_rendered.append(accumulate_assets)
    render(PJXGraph(id="g", nodes="<div></div>"), session)
    assert {p.name for p in session.js_assets} == {"pjx_graph.js"}
    assert {p.name for p in session.css_assets} == {"pjx_graph.css"}


def test_asset_defines_pjx_graph_and_leaks_no_d3(graph_page, page_errors):
    assert graph_page.evaluate("typeof window.pjx.graph") == "object"
    assert graph_page.evaluate("typeof window.__pjxD3") == "undefined"
    assert graph_page.evaluate("typeof window.d3") == "undefined"
    assert page_errors == []


def test_reloading_keeps_the_same_graph_namespace(graph_page, page_errors):
    graph_page.evaluate("window.pjx.graph.marker = 1")
    graph_page.add_script_tag(content=ASSET.read_text(encoding="utf-8"))
    assert graph_page.evaluate("window.pjx.graph.marker") == 1
    assert page_errors == []


def test_loading_keeps_an_existing_pjx_namespace(page: Page):
    page.set_content("<body></body>")
    page.add_script_tag(content="window.pjx = {other: 1};")
    page.add_script_tag(content=ASSET.read_text(encoding="utf-8"))
    assert page.evaluate("window.pjx.other") == 1
    assert page.evaluate("typeof window.pjx.graph") == "object"
